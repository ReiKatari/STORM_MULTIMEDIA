export function resolveFanFilmUrl(title) {
  if (!title) return '';
  const norm = String(title)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s*4k/gi, '')
    .replace(/[^a-zа-я0-9]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  if (KNOWN_FANFILM_URLS[norm]) return KNOWN_FANFILM_URLS[norm];
  return '';
}


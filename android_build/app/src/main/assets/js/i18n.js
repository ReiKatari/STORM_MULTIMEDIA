export function t(key) {
  if (!key) return '';
  const dict = translations[currentLang] || translations.ru;
  if (dict && dict[key]) return dict[key];
  if (translations.ru && translations.ru[key]) return translations.ru[key];
  if (translations.en && translations.en[key]) return translations.en[key];
  if (HUMAN_FALLBACKS[key]) return HUMAN_FALLBACKS[key];
  
  // Guard against raw snake_case or technical keys leaking into UI
  if (typeof key === 'string' && (key.includes('_') || /^[a-z]+[A-Z]/.test(key))) {
    const cleaned = key.replace(/^(?:bookmarks_subtab_|stats_|status_|tab_|filter_|sort_|btn_|msg_|card_menu_|rail_|profile_)/, '')
                       .replace(/_/g, ' ');
    return cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
  }
  return key;
}

export function formatDate(timestamp) {
  if (!timestamp) return '';
  const date = new Date(timestamp);
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const year = date.getFullYear();
  return `${day}.${month}.${year}`;
}

export function formatTime(timestamp) {
  if (!timestamp) return '';
  const date = new Date(timestamp);
  const hours = String(date.getHours()).padStart(2, '0');
  const minutes = String(date.getMinutes()).padStart(2, '0');
  return `${hours}:${minutes}`;
}

export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const tr = t(key);
      if (tr && tr !== key) el.textContent = tr;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      el.title = t(key);
    }
  });
}
